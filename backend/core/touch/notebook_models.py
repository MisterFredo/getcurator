# ============================================================
# CORPUS NOTEBOOK
# ============================================================
class TouchCorpusNotebook(
    StrictTouchNotebookModel,
):

    subject: str

    objective: str

    corpus_summary: str

    executive_summary: list[
        TouchNotebookExecutiveSummaryItem
    ] = Field(
        default_factory=list,
    )

    sections: list[
        TouchNotebookSection
    ] = Field(
        default_factory=list,
    )

    notes: list[
        TouchEvidenceNote
    ] = Field(
        default_factory=list,
    )

    events: list[
        TouchNotebookEvent
    ] = Field(
        default_factory=list,
    )

    timeline: list[
        TouchNotebookTimelineItem
    ] = Field(
        default_factory=list,
    )

    dimensions: list[
        TouchNotebookDimension
    ] = Field(
        default_factory=list,
    )

    validated_numbers: list[
        TouchNotebookNumber
    ] = Field(
        default_factory=list,
    )

    quarantined_numbers: list[
        TouchQuarantinedNumber
    ] = Field(
        default_factory=list,
    )

    contradictions: list[
        TouchNotebookContradiction
    ] = Field(
        default_factory=list,
    )

    corpus_strengths: list[str] = Field(
        default_factory=list,
    )

    corpus_limits: list[str] = Field(
        default_factory=list,
    )

