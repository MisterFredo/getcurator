class TouchNotebookNumberEntity(
    StrictTouchNotebookModel,
):

    entity_type: str | None = None

    entity_id: str | None = None

    entity_label: str | None = None


# ============================================================
# CERTIFIED NUMBER
# ============================================================

class TouchNotebookNumber(
    StrictTouchNotebookModel,
):
    """
    Touch representation of one effectively ACCEPTED
    Number observation.

    The values are copied from the canonical Numbers
    service and are not generated by the Touch LLM.
    """

    number_id: str

    id_content: str

    label: str | None = None

    metric_type: str | None = None

    value: Any = None

    value_min: Any = None

    value_max: Any = None

    unit: str | None = None

    scale: str | None = None

    zone: str | None = None

    period_label: str | None = None

    value_status: str | None = None

    confidence: float = 0

    entities: list[
        TouchNotebookNumberEntity
    ] = Field(
        default_factory=list,
    )

    source_content_ids: list[str] = Field(
        default_factory=list,
    )


