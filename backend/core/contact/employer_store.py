"""One BigQuery transaction per employer decision batch, guarded and replay-safe."""
import json
from core.contact import service as contacts
from core.contact.company_follow import sync_sql
TABLE=f'{contacts.BASE}.RATECARD_CONTACT_EMPLOYER_CHECK'

def write(run_id,items):
    if not items:return []
    return contacts.query(f'''CREATE TEMP TABLE decisions AS
      SELECT JSON_VALUE(j,'$.id_contact') ID_CONTACT,JSON_VALUE(j,'$.profile_url') PROFILE_URL,
        TIMESTAMP(JSON_VALUE(j,'$.expected_updated_at')) EXPECTED_AT,
        JSON_VALUE(j,'$.old_company') OLD_COMPANY,JSON_VALUE(j,'$.target_company') TARGET_COMPANY,
        JSON_VALUE(j,'$.status') STATUS,JSON_VALUE(j,'$.source_name') SOURCE_NAME,
        JSON_VALUE(j,'$.source_url') SOURCE_URL,JSON_VALUE(j,'$.reason') REASON,
        JSON_VALUE(j,'$.op_token') OP_TOKEN,JSON_VALUE(j,'$.expected_check_run') EXPECTED_CHECK_RUN
      FROM UNNEST(JSON_QUERY_ARRAY(PARSE_JSON(@items))) j;
      BEGIN TRANSACTION;
      CREATE TEMP TABLE current_aff AS
        SELECT a.ID_CONTACT,ANY_VALUE(a.ID_COMPANY) AS ID_COMPANY,COUNT(*) AS N
        FROM `{contacts.AFFILIATION}` a WHERE a.ENDED_AT IS NULL
          AND a.ID_CONTACT IN(SELECT ID_CONTACT FROM decisions) GROUP BY a.ID_CONTACT;
      CREATE TEMP TABLE checked AS
        SELECT d.*, e.OP_TOKEN=d.OP_TOKEN AS ALREADY_DONE,
          c.ID_CONTACT IS NOT NULL AND c.IS_ACTIVE=TRUE AND c.UPDATED_AT=d.EXPECTED_AT
          AND c.LINKEDIN_URL=d.PROFILE_URL AND COALESCE(a.N,0)<=1
          AND COALESCE(a.ID_COMPANY,'')=COALESCE(d.OLD_COMPANY,'')
          AND (d.TARGET_COMPANY IS NULL OR co.ID_COMPANY IS NOT NULL)
          AND (d.EXPECTED_CHECK_RUN IS NULL OR e.ID_RUN=d.EXPECTED_CHECK_RUN) AS VALID
        FROM decisions d LEFT JOIN `{contacts.CONTACT}` c ON c.ID_CONTACT=d.ID_CONTACT
        LEFT JOIN current_aff a ON a.ID_CONTACT=d.ID_CONTACT
        LEFT JOIN `{contacts.COMPANY}` co ON co.ID_COMPANY=d.TARGET_COMPANY
        LEFT JOIN `{TABLE}` e ON e.ID_CONTACT=d.ID_CONTACT;
      CREATE TEMP TABLE employer_changes AS SELECT * FROM checked
        WHERE VALID AND NOT COALESCE(ALREADY_DONE,FALSE) AND STATUS IN ('MOVED','UNMATCHED','REVIEW');
      UPDATE `{contacts.WATCH}` SET IS_ACTIVE=FALSE,UPDATED_AT=CURRENT_TIMESTAMP()
        WHERE ID_CONTACT IN(SELECT ID_CONTACT FROM employer_changes) AND IS_ACTIVE=TRUE;
      UPDATE `{contacts.AFFILIATION}` SET ENDED_AT=CURRENT_TIMESTAMP(),UPDATED_AT=CURRENT_TIMESTAMP()
        WHERE ID_CONTACT IN(SELECT ID_CONTACT FROM employer_changes WHERE STATUS IN ('MOVED','UNMATCHED')) AND ENDED_AT IS NULL;
      MERGE `{contacts.AFFILIATION}` a USING (SELECT * FROM employer_changes WHERE STATUS='MOVED') d
        ON a.ID_CONTACT=d.ID_CONTACT AND a.ID_COMPANY=d.TARGET_COMPANY AND a.ENDED_AT IS NULL
        WHEN NOT MATCHED THEN INSERT(ID_CONTACT_COMPANY,ID_CONTACT,ID_COMPANY,JOB_TITLE,STARTED_AT,ENDED_AT,CREATED_AT,UPDATED_AT)
          VALUES(CONCAT('employer-',d.OP_TOKEN),d.ID_CONTACT,d.TARGET_COMPANY,NULL,CURRENT_TIMESTAMP(),NULL,CURRENT_TIMESTAMP(),CURRENT_TIMESTAMP());
      UPDATE `{contacts.CONTACT}` SET UPDATED_AT=CURRENT_TIMESTAMP(),
          JOB_TITLE=IF(ID_CONTACT IN(SELECT ID_CONTACT FROM employer_changes WHERE STATUS IN ('MOVED','UNMATCHED')),NULL,JOB_TITLE)
        WHERE ID_CONTACT IN(SELECT ID_CONTACT FROM employer_changes);
      {sync_sql("c.ID_CONTACT IN (SELECT ID_CONTACT FROM employer_changes WHERE STATUS='MOVED')")}
      MERGE `{TABLE}` t USING (
        SELECT d.*,c.UPDATED_AT AS CONTACT_UPDATED_AT,
          IF(d.VALID,d.STATUS,'CONFLICT') AS FINAL_STATUS
        FROM checked d LEFT JOIN `{contacts.CONTACT}` c ON c.ID_CONTACT=d.ID_CONTACT
        WHERE NOT COALESCE(d.ALREADY_DONE,FALSE)
      ) s ON t.ID_CONTACT=s.ID_CONTACT
      WHEN MATCHED THEN UPDATE SET ID_RUN=@run,PROFILE_URL=s.PROFILE_URL,OLD_COMPANY=s.OLD_COMPANY,
        SOURCE_COMPANY_NAME=IF(s.STATUS='ERROR',t.SOURCE_COMPANY_NAME,s.SOURCE_NAME),SOURCE_COMPANY_URL=IF(s.STATUS='ERROR',t.SOURCE_COMPANY_URL,s.SOURCE_URL),MATCHED_ID_COMPANY=s.TARGET_COMPANY,
        STATUS=IF(s.VALID AND s.STATUS='ERROR' AND t.STATUS IN ('UNMATCHED','REVIEW'),t.STATUS,s.FINAL_STATUS),LAST_ATTEMPT_STATUS=s.FINAL_STATUS,REASON=IF(s.VALID,s.REASON,'Fiche modifiée pendant le contrôle : aucune modification appliquée'),
        CHECKED_AT=CURRENT_TIMESTAMP(),CONTACT_UPDATED_AT=s.CONTACT_UPDATED_AT,OP_TOKEN=s.OP_TOKEN,
        LAST_VERIFIED_AT=IF(s.VALID AND s.STATUS IN ('CONFIRMED','MOVED','UNMATCHED'),CURRENT_TIMESTAMP(),t.LAST_VERIFIED_AT)
      WHEN NOT MATCHED THEN INSERT(ID_CONTACT,ID_RUN,PROFILE_URL,OLD_COMPANY,SOURCE_COMPANY_NAME,SOURCE_COMPANY_URL,
        MATCHED_ID_COMPANY,STATUS,LAST_ATTEMPT_STATUS,REASON,CHECKED_AT,LAST_VERIFIED_AT,CONTACT_UPDATED_AT,OP_TOKEN)
        VALUES(s.ID_CONTACT,@run,s.PROFILE_URL,s.OLD_COMPANY,s.SOURCE_NAME,s.SOURCE_URL,s.TARGET_COMPANY,s.FINAL_STATUS,s.FINAL_STATUS,
          IF(s.VALID,s.REASON,'Fiche modifiée pendant le contrôle : aucune modification appliquée'),CURRENT_TIMESTAMP(),
          IF(s.VALID AND s.STATUS IN ('CONFIRMED','MOVED','UNMATCHED'),CURRENT_TIMESTAMP(),NULL),s.CONTACT_UPDATED_AT,s.OP_TOKEN);
      COMMIT TRANSACTION;
      SELECT e.*,c.UPDATED_AT AS CURRENT_UPDATED_AT FROM `{TABLE}` e
        LEFT JOIN `{contacts.CONTACT}` c ON c.ID_CONTACT=e.ID_CONTACT
        WHERE e.ID_CONTACT IN(SELECT ID_CONTACT FROM decisions);''',
      [contacts.p('run','STRING',run_id),contacts.p('items','STRING',json.dumps(items,ensure_ascii=False))])
