"""Set-based company/contact follow propagation. No scan and no USER writes."""
from config import BQ_PROJECT, BQ_DATASET

BASE = f'{BQ_PROJECT}.{BQ_DATASET}'

def sync_sql(scope='TRUE'):
    # scope is internal SQL only, never supplied by an API caller.
    return f"""
    CREATE TEMP TABLE follow_targets AS
      SELECT c.ID_CONTACT, a.ID_COMPANY, c.LINKEDIN_URL,
        TRIM(CONCAT(COALESCE(c.FIRST_NAME,''),' ',COALESCE(c.LAST_NAME,''))) AS AUTHOR,
        COALESCE(m.IS_ENABLED,FALSE) AND co.IS_ACTIVE=TRUE AND c.IS_ACTIVE=TRUE
          AND REGEXP_CONTAINS(COALESCE(c.LINKEDIN_URL,''),r'^https://www\\.linkedin\\.com/in/[^/?#]+$') AS ENABLED
      FROM `{BASE}.RATECARD_CONTACT` c
      JOIN `{BASE}.RATECARD_CONTACT_COMPANY` a ON a.ID_CONTACT=c.ID_CONTACT AND a.ENDED_AT IS NULL
      JOIN `{BASE}.RATECARD_COMPANY` co ON co.ID_COMPANY=a.ID_COMPANY
      LEFT JOIN `{BASE}.RATECARD_COMPANY_MENTION_CONFIG` m ON m.ID_COMPANY=a.ID_COMPANY
      WHERE {scope}
      QUALIFY ROW_NUMBER() OVER(PARTITION BY c.ID_CONTACT ORDER BY a.STARTED_AT DESC,a.ID_CONTACT_COMPANY)=1;
    CREATE TEMP TABLE follow_points AS
      SELECT t.*, COALESCE(w.ID_COMPANY_WATCH,CONCAT('contact-',TO_HEX(SHA256(CONCAT(t.ID_CONTACT,'|',t.ID_COMPANY,'|',t.LINKEDIN_URL))))) AS WATCH_ID
      FROM follow_targets t LEFT JOIN `{BASE}.RATECARD_COMPANY_WATCH` w
        ON w.ID_CONTACT=t.ID_CONTACT AND w.ID_COMPANY=t.ID_COMPANY AND w.SOURCE_URL=t.LINKEDIN_URL
      WHERE t.ENABLED=TRUE
      QUALIFY ROW_NUMBER() OVER(PARTITION BY t.ID_CONTACT ORDER BY w.IS_ACTIVE DESC,w.UPDATED_AT DESC,w.ID_COMPANY_WATCH)=1;
    ASSERT NOT EXISTS (
      SELECT 1 FROM follow_points p JOIN `{BASE}.RATECARD_COMPANY_WATCH` w
        ON w.ID_COMPANY=p.ID_COMPANY AND w.SOURCE_URL=p.LINKEDIN_URL
      WHERE w.ID_CONTACT IS NULL OR w.ID_CONTACT!=p.ID_CONTACT
    ) AS 'Un profil possède déjà un point de collecte non associé au contact : rattacher ou nettoyer ce point avant activation';
    UPDATE `{BASE}.RATECARD_COMPANY_WATCH` w SET IS_ACTIVE=FALSE,UPDATED_AT=CURRENT_TIMESTAMP()
      WHERE w.ID_CONTACT IN (SELECT ID_CONTACT FROM follow_targets) AND w.IS_ACTIVE=TRUE
        AND w.ID_COMPANY_WATCH NOT IN (SELECT WATCH_ID FROM follow_points);
    MERGE `{BASE}.RATECARD_COMPANY_WATCH` w USING follow_points p ON w.ID_COMPANY_WATCH=p.WATCH_ID
      WHEN MATCHED AND w.IS_ACTIVE IS DISTINCT FROM TRUE THEN UPDATE SET IS_ACTIVE=TRUE,UPDATED_AT=CURRENT_TIMESTAMP()
      WHEN NOT MATCHED THEN INSERT(ID_COMPANY_WATCH,ID_COMPANY,ID_CONTACT,LABEL,SOURCE_TYPE,SOURCE_URL,SOURCE_ROLE,AUTHOR_NAME,COLLECTION_METHOD,COLLECTION_CONFIG,IS_ACTIVE,CREATED_AT,UPDATED_AT)
        VALUES(p.WATCH_ID,p.ID_COMPANY,p.ID_CONTACT,CONCAT('LinkedIn — ',p.AUTHOR),'LINKEDIN',p.LINKEDIN_URL,'EMPLOYEE',p.AUTHOR,'BRIGHTDATA',PARSE_JSON('{{}}'),TRUE,CURRENT_TIMESTAMP(),CURRENT_TIMESTAMP());
    UPDATE `{BASE}.RATECARD_CONTACT` SET UPDATED_AT=CURRENT_TIMESTAMP()
      WHERE ID_CONTACT IN (SELECT ID_CONTACT FROM follow_targets);
    """

def default_follow(company_id, linkedin_url, active=True):
    if not company_id or not linkedin_url or not active:
        return False
    from core.contact import service as contacts
    rows = contacts.query(f'''SELECT COALESCE(m.IS_ENABLED,FALSE) AND c.IS_ACTIVE=TRUE AS ENABLED
      FROM `{BASE}.RATECARD_COMPANY` c
      LEFT JOIN `{BASE}.RATECARD_COMPANY_MENTION_CONFIG` m ON m.ID_COMPANY=c.ID_COMPANY
      WHERE c.ID_COMPANY=@company LIMIT 1''', [contacts.p('company','STRING',company_id)])
    return bool(rows and rows[0]['ENABLED'])
